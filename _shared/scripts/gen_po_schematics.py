def write_po_kit(topic, po):
    d = os.path.join(REPO, topic, "01_zadel/registration_PO")
    os.makedirs(d, exist_ok=True)
    
    with open(os.path.join(d, "zayavka_registracia_PO.md"), 'w', encoding='utf-8') as f:
        f.write(f"""# Заявка на государственную регистрацию программы для ЭВМ

## 1. Наименование ПО
{po['po_name']} версия {po['version']}

## 2. Назначение
{po['purpose']}

## 3. Платформа
{po['platform']}

## 4. Язык(и) программирования
{po['lang']}

## 5. Функциональные возможности
""")
        for i, fn in enumerate(po['functions'], 1):
            f.write(f"{i}. {fn}\n")
        f.write(f"""
## 6. Условия использования
Программное обеспечение разработано в рамках НИОКТР, финансируемого грантом
Фонда содействия инновациям (ФСИ «Старт-Пром-1», очередь 4).

## 7. Интеллектуальная собственность
Права на ПО принадлежат исполнителю НИОКТР. Патентование РИД финансируется
из собственных средств заявителя и не включено в бюджет гранта.

## 8. Аннотация
{po['po_name']} — программное обеспечение, обеспечивающее {po['purpose'].lower()}.
Версия {po['version']} является первой публичной версией, прошедшей стендовые испытания.

---
*Проект заявки. Дата: октябрь 2026 г. Без подписей.*
""")


def write_schematic_md(topic, sch):
    d = os.path.join(REPO, topic, "01_zadel/patent_PM/chertezhi")
    os.makedirs(d, exist_ok=True)
    
    with open(os.path.join(d, "schematic.md"), 'w', encoding='utf-8') as f:
        f.write(f"# {sch['title']}\n\n")
        f.write("## Компоненты\n\n")
        f.write("| Обозначение | Тип / Модель | Назначение |\n")
        f.write("|---|---|---|\n")
        for ref, typ, desc in sch['components']:
            f.write(f"| {ref} | {typ} | {desc} |\n")
        f.write("\n## Соединения\n\n")
        f.write("| От | Куда | Интерфейс |\n")
        f.write("|---|---|---|\n")
        for src, dst, intf in sch['connections']:
            f.write(f"| {src} | {dst} | {intf} |\n")
        f.write("\n---\n*Текстовое описание электрической схемы. "
                "Графическая схема выполнена в формате DXF.*\n")


